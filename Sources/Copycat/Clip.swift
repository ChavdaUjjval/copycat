import AppKit
import CryptoKit
import UniformTypeIdentifiers

enum PasteboardTypes {
    static let remote = "com.apple.is-remote-clipboard"
    static let fileURL = NSPasteboard.PasteboardType.fileURL.rawValue
    static let plainText = NSPasteboard.PasteboardType.string.rawValue
    static let rtfd: Set<String> = ["com.apple.flat-rtfd", "NeXT RTFD pasteboard type"]
    static let standardImages: Set<String> = ["public.png", "public.jpeg", "public.heic", "public.tiff"]
    // Copies that password managers and other apps mark as secret or temporary (nspasteboard.org).
    static let ignored: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]
}

enum Limits {
    static let typeBytes = 20_000_000       // skip any single representation bigger than this
    static let storeBytes = 250_000_000     // total history size before old items are dropped
    static let keptFileBytes = 200_000_000  // largest iPhone/iPad file the shelf keeps a copy of
}

enum Storage {
    static let directory: URL = {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Copycat")
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }()
    static let history = directory.appendingPathComponent("history.plist")
    static let keptFiles = directory.appendingPathComponent("files")   // iPhone files and dropped photos
    static let exports = directory.appendingPathComponent("exports")   // images/text written out for dragging
}

extension URL {
    var contentType: UTType? { UTType(filenameExtension: pathExtension) }
    var isImage: Bool { contentType?.conforms(to: .image) ?? false }
    var isVideo: Bool { contentType?.conforms(to: .audiovisualContent) ?? false }
    var fileSize: Int { (try? resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? Int.max }
}

// MARK: - Clip

enum Kind { case text, media, files }

struct Clip: Identifiable, Codable, Equatable {
    var id = UUID()
    var date = Date()
    var fromDevice = false
    var pinned = false
    var key = ""
    var text: String?
    var files: [String] = []
    var thumb: Data?
    var payload: [[String: Data]] = []
    var keptBytes: Int?     // size of files copied into the shelf's own storage
    var sourceApp: String?  // bundle ID of the Mac app it was copied from

    var title: String {
        if !files.isEmpty { return files.joined(separator: ", ") }
        if let t = text?.trimmingCharacters(in: .whitespacesAndNewlines), !t.isEmpty { return t }
        return thumb != nil ? "Image" : "Item"
    }

    var bytes: Int { payload.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } } + (keptBytes ?? 0) }

    var fileURLs: [URL] {
        payload.compactMap { $0[PasteboardTypes.fileURL].flatMap { String(data: $0, encoding: .utf8) }.flatMap(URL.init(string:)) }
    }

    var isVideo: Bool { fileURLs.first?.isVideo ?? false }

    // A copied web address, shown as a link card.
    var link: URL? {
        guard files.isEmpty, thumb == nil,
              let t = text?.trimmingCharacters(in: .whitespacesAndNewlines), !t.contains(where: \.isWhitespace),
              let url = URL(string: t), ["http", "https"].contains(url.scheme?.lowercased() ?? ""), url.host != nil
        else { return nil }
        return url
    }

    var kind: Kind {
        let urls = fileURLs
        if !urls.isEmpty { return urls.allSatisfy { $0.isImage || $0.isVideo } ? .media : .files }
        return thumb != nil ? .media : .text
    }

    // The best image representation on the clip.
    var imageData: (type: String, data: Data)? {
        guard let item = payload.first else { return nil }
        for t in ["com.compuserve.gif", "public.jpeg", "public.png", "public.heic"] {
            if let d = item[t] { return (t, d) }
        }
        if let tiff = item["public.tiff"], let png = Images.png(from: tiff) { return (UTType.png.identifier, png) }
        if let other = item.first(where: { UTType($0.key)?.conforms(to: .image) == true })?.value,
           let png = Images.png(from: other) {
            return (UTType.png.identifier, png)
        }
        return nil
    }

    // A copied colour code such as #F5568A, shown with a swatch.
    var color: NSColor? {
        guard files.isEmpty, thumb == nil, let t = text?.trimmingCharacters(in: .whitespacesAndNewlines),
              t.first == "#", t.count == 4 || t.count == 7 else { return nil }
        var hex = String(t.dropFirst())
        guard hex.allSatisfy(\.isHexDigit) else { return nil }
        if hex.count == 3 { hex = hex.map { "\($0)\($0)" }.joined() }
        guard let v = UInt32(hex, radix: 16) else { return nil }
        return NSColor(srgbRed: CGFloat(v >> 16 & 0xFF) / 255, green: CGFloat(v >> 8 & 0xFF) / 255,
                       blue: CGFloat(v & 0xFF) / 255, alpha: 1)
    }

    static func fileKey(_ urls: [URL]) -> String { "f:" + urls.map(\.path).joined(separator: "|") }
}

// MARK: - Capturing

extension Clip {
    // Reads the pasteboard into a clip. Reading the data here is also what pulls an
    // iPhone copy over before macOS discards it.
    static func capture(_ pb: NSPasteboard) -> Clip? {
        let types = (pb.types ?? []).map(\.rawValue)
        if types.isEmpty || types.contains(where: PasteboardTypes.ignored.contains) { return nil }
        var clip = Clip()
        clip.fromDevice = types.contains(PasteboardTypes.remote)

        for item in pb.pasteboardItems ?? [] {
            var dict: [String: Data] = [:]
            for t in item.types where t.rawValue != PasteboardTypes.remote && !t.rawValue.hasPrefix("dyn.") {
                if let d = item.data(forType: t), d.count <= Limits.typeBytes { dict[t.rawValue] = d }
            }
            if !dict.isEmpty { clip.payload.append(dict) }
        }
        guard let first = clip.payload.first, clip.bytes > 0 else { return nil }   // ignore empty copies

        var urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        if clip.fromDevice && !urls.isEmpty { urls = clip.keepFiles(urls) }
        clip.files = urls.map(\.lastPathComponent)
        clip.text = pb.string(forType: .string)
        clip.normalize()

        if urls.isEmpty, first.keys.contains(where: { UTType($0)?.conforms(to: .image) == true }) {
            clip.thumb = clip.imageData.flatMap { Images.thumbnail(data: $0.data) }
        } else if let file = urls.first, file.isImage, file.fileSize <= Limits.keptFileBytes {
            clip.thumb = Images.thumbnail(file: file)
        }

        if !urls.isEmpty {
            clip.key = fileKey(urls)
        } else if let t = clip.text, !t.isEmpty, clip.thumb == nil {
            clip.key = "t:" + t
        } else {
            var hash = SHA256()
            for (t, d) in clip.payload[0].sorted(by: { $0.key < $1.key }) {
                hash.update(data: Data(t.utf8))
                hash.update(data: d)
            }
            clip.key = "h:" + hash.finalize().map { String(format: "%02x", $0) }.joined()
        }
        return clip
    }

    // Makes a clip usable by every app:
    // • images in formats many apps can't take (WebP, AVIF, GIF…) also get a PNG version;
    // • rich text with no plain-text version (e.g. Live Text from iPhone photos) gets one.
    mutating func normalize() {
        for i in payload.indices {
            let item = payload[i]
            if Set(item.keys).isDisjoint(with: PasteboardTypes.standardImages),
               let image = item.first(where: { UTType($0.key)?.conforms(to: .image) == true })?.value,
               let png = Images.png(from: image), png.count <= Limits.typeBytes {
                payload[i][UTType.png.identifier] = png
            }
            if item[PasteboardTypes.plainText] == nil, item[PasteboardTypes.fileURL] == nil {
                for t in ["com.apple.flat-rtfd", "public.rtf"] {
                    if let d = item[t], let plain = Self.plainText(from: d, type: t) {
                        payload[i][PasteboardTypes.plainText] = Data(plain.utf8)
                        if (text ?? "").isEmpty { text = plain }
                        break
                    }
                }
            }
        }
    }

    // Copies iPhone/iPad files out of macOS's temporary Universal Clipboard folder into the
    // shelf's own storage, points the clip at those copies, and returns the new URLs.
    mutating func keepFiles(_ urls: [URL]) -> [URL] {
        let fm = FileManager.default
        let dir = Storage.keptFiles.appendingPathComponent(id.uuidString)
        var moved: [String: URL] = [:]
        var kept = 0
        for url in urls where url.fileSize <= Limits.keptFileBytes {
            let dest = dir.appendingPathComponent(url.lastPathComponent)
            do {
                try fm.createDirectory(at: dir, withIntermediateDirectories: true)
                try fm.copyItem(at: url, to: dest)
                moved[url.standardizedFileURL.path] = dest
                kept += dest.fileSize
            } catch { continue }
        }
        guard !moved.isEmpty else { return urls }
        keptBytes = kept
        for i in payload.indices {
            guard let d = payload[i][PasteboardTypes.fileURL], let s = String(data: d, encoding: .utf8),
                  let old = URL(string: s), let new = moved[old.standardizedFileURL.path] else { continue }
            payload[i][PasteboardTypes.fileURL] = Data(new.absoluteString.utf8)
        }
        attachImageData()
        return urls.map { moved[$0.standardizedFileURL.path] ?? $0 }
    }

    // Carries the picture itself alongside each image file, so apps that take
    // pictures rather than files (Messages, Notes, Mail) can paste it.
    mutating func attachImageData() {
        for i in payload.indices {
            guard let d = payload[i][PasteboardTypes.fileURL], let s = String(data: d, encoding: .utf8),
                  let url = URL(string: s), let type = url.contentType, type.conforms(to: .image),
                  url.fileSize <= Limits.typeBytes, let data = try? Data(contentsOf: url) else { continue }
            payload[i][type.identifier] = data
        }
    }

    private static func plainText(from data: Data, type: String) -> String? {
        let attributed: NSAttributedString?
        switch type {
        case "com.apple.flat-rtfd": attributed = NSAttributedString(rtfd: data, documentAttributes: nil)
        case "public.rtf": attributed = NSAttributedString(rtf: data, documentAttributes: nil)
        default: attributed = nil
        }
        let text = attributed?.string.replacingOccurrences(of: "\u{FFFC}", with: "")
            .trimmingCharacters(in: .whitespacesAndNewlines)
        return text?.isEmpty == false ? text : nil
    }
}

// MARK: - Images

// Image conversion with ImageIO, safe to use from any thread.
enum Images {
    static let thumbnailSize = 480

    static func png(_ image: CGImage) -> Data? {
        let data = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(data, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dest, image, nil)
        return CGImageDestinationFinalize(dest) ? data as Data : nil
    }

    static func png(from data: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
        return png(image)
    }

    static func thumbnail(data: Data) -> Data? { thumbnail(CGImageSourceCreateWithData(data as CFData, nil)) }
    static func thumbnail(file: URL) -> Data? { thumbnail(CGImageSourceCreateWithURL(file as CFURL, nil)) }

    private static func thumbnail(_ source: CGImageSource?) -> Data? {
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: thumbnailSize,
        ]
        guard let source, let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return png(image)
    }
}
